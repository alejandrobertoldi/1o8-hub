#!/usr/bin/env bash
# Idempotent repository bootstrap for the Cursor Cloud environment.
# Runs after checkout. Prepares node deps, a local PostgreSQL database with the
# app schema, and a seeded owner user for local development.
set -euo pipefail

# Always operate from the repository root (this script lives in .cursor/).
cd "$(dirname "$0")/.."

DB_URL="postgresql://mfhub:mfhub@127.0.0.1:5432/mfhub"

echo "==> Installing node dependencies"
npm ci

echo "==> Starting local PostgreSQL"
bash .cursor/start.sh

echo "==> Ensuring database role and database exist"
sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='mfhub'" | grep -q 1 \
  || sudo -u postgres psql -c "CREATE USER mfhub WITH PASSWORD 'mfhub' CREATEDB;"
sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='mfhub'" | grep -q 1 \
  || sudo -u postgres psql -c "CREATE DATABASE mfhub OWNER mfhub;"

if [ ! -f .env.local ]; then
  echo "==> Writing .env.local (dev-only secrets)"
  SECRET="$(openssl rand -base64 32)"
  cat > .env.local <<EOF
# Local development environment (Cursor Cloud) - generated by .cursor/install.sh
DATABASE_URL="${DB_URL}"

NEXTAUTH_URL="http://localhost:3000"
NEXTAUTH_SECRET="${SECRET}"
AUTH_SECRET="${SECRET}"

# Placeholder Google OAuth creds (real values needed only for live OAuth login)
GOOGLE_CLIENT_ID="dev-placeholder"
GOOGLE_CLIENT_SECRET="dev-placeholder"

MONTHLY_REPORT_JWT_SECRET="dev-local-change-me"
EOF
else
  echo "==> .env.local already present, leaving it untouched"
fi

# tsx/drizzle scripts need DATABASE_URL in the real env because ESM import
# hoisting evaluates src/lib/db before dotenv.config() runs.
export DATABASE_URL="${DB_URL}"

# Apply the schema only when it is not already present. drizzle-kit push is
# interactive when it must reconcile an already-populated database (it asks
# before truncating), which would hang a non-TTY build. On a fresh database it
# applies cleanly and non-interactively.
SCHEMA_APPLIED="$(sudo -u postgres psql -d mfhub -tAc "SELECT to_regclass('public.users') IS NOT NULL")"
if [ "${SCHEMA_APPLIED}" = "t" ]; then
  echo "==> Schema already present, skipping db:push"
else
  echo "==> Applying database schema (drizzle db:push)"
  npm run db:push
fi

echo "==> Seeding owner user dev@localhost.test"
npm run create-admin dev@localhost.test || true
sudo -u postgres psql -d mfhub -c \
  "UPDATE users SET role='owner', is_super_admin=true, name='Dev Admin' WHERE email='dev@localhost.test';" || true

echo "==> Install complete"
